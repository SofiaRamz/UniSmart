def _enable_pgvector(conn) -> bool:
    backend = get_settings().VECTOR_BACKEND.lower()
    if backend == "array":
        return False
    try:
        with conn.begin_nested():
            conn.exec_driver_sql("CREATE EXTENSION IF NOT EXISTS vector")
        return True
    except Exception as exc:
        if backend == "pgvector":
            raise RuntimeError("VECTOR_BACKEND=pgvector pero la extensión 'vector' no está disponible") from exc
        log.warning("pgvector no disponible: se usará double precision[] y similitud en Python (%s)", exc)
        return False


